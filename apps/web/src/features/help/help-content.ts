export function getHelpGuides(user: Pick<AuthUser, 'role' | 'accessScopes'>): HelpGuide[] {
  switch (user.role) {
    case 'OWNER':
      return [helpGuides.mvo, helpGuides.manager, helpGuides.accountant];
    case 'ACCOUNTANT':
      return [helpGuides.accountant];
    case 'ORG_MANAGER':
      return [helpGuides.manager];
    case 'MVO':
      return user.accessScopes?.length
        ? [helpGuides.mvo, helpGuides.manager]
        : [helpGuides.mvo];
  }
}
