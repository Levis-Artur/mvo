export type HelpContentBlock =
  | { type: 'paragraph'; text: string }
  | { type: 'list'; items: string[]; ordered?: boolean }
  | { type: 'warning'; text: string; items?: string[] };

export type HelpSection = {
  id: string;
  title: string;
  blocks: HelpContentBlock[];
};

export type HelpGuide = {
  id: HelpGuideId;
  title: string;
  introduction: string;
  quickStart: string[];
  sections: HelpSection[];
};

const list = (items: string[], ordered = false): HelpContentBlock => ({ type: 'list', items, ordered });
const paragraph = (text: string): HelpContentBlock => ({ type: 'paragraph', text });

